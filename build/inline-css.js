// Wraps the compiled Tailwind CSS (static/output.css) into a Go html/template
// partial (reports/_styles.html) that report templates pull in with
//   {{ template "reportstyles" . }}
//
// Inlining rather than <link>-ing keeps the styles working when the report is
// rendered through headless Chrome for PDF (no network round-trip, no reliance
// on the static-file mount path).
//
// Run via `npm run build` (or `make css`), never by hand.
//
// Lives in build/ (not scripts/) — scripts/ is the sobek data-action dir.

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const cssPath = path.join(root, 'static', 'output.css');
const outPath = path.join(root, 'reports', 'styles.partial.html');

const css = fs.readFileSync(cssPath, 'utf8').trimEnd();

// A literal `}}` in CSS text is harmless (Go's lexer only treats it specially
// after an opening `{{`), but `{{` would start a template action.
if (css.includes('{{')) {
  throw new Error('compiled CSS contains a `{{` — cannot inline safely');
}

const partial = `{{- /* GENERATED by build/inline-css.js from static/output.css — do not edit. Run: make css */ -}}
{{ define "reportstyles" }}<style>
${css}
</style>{{ end }}
`;

fs.writeFileSync(outPath, partial);
console.log(`wrote ${path.relative(root, outPath)} (${css.length} bytes of CSS)`);
